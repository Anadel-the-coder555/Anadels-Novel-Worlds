const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const saved = {};
const context = { localStorage: { getItem: k => saved[k], setItem: (k, v) => saved[k] = v } };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'tournament.js'), 'utf8'), context);
const cup = new context.GravityCup();
cup.start('rings', true);
cup.award(80, 'ring'); assert.equal(cup.score, 0, 'countdown blocks scoring');
cup.tick(3); assert.equal(cup.running, true);
for (let i = 0; i < 4; i++) cup.award(80, 'ring');
assert.equal(cup.score, 400, 'fourth pickup doubles the score');
cup.paused = true; cup.tick(20); cup.award(80, 'ring');
assert.equal(cup.time, 60); assert.equal(cup.score, 400);
cup.paused = false; cup.tick(8); assert.equal(cup.combo, 0);
cup.tick(52); assert.equal(cup.finished, true); assert.equal(cup.medal, 'Bronze');
cup.finish(); assert.equal(cup.history.length, 1, 'finish only counts once');
assert.equal(cup.next(), true); assert.equal(cup.event, 'parkour');
cup.tick(3); cup.award(900, 'zone'); cup.tick(60);
assert.equal(cup.next(), true); assert.equal(cup.event, 'style');
cup.tick(3);
cup.skill('jump'); cup.skill('redirect'); cup.skill('redirect'); cup.skill('flip');
cup.landed('floor'); assert.equal(cup.score, 0, 'same-surface landing scores nothing');
cup.skill('jump'); cup.skill('redirect'); cup.skill('flip'); cup.landed('ceil');
assert.equal(cup.score, 220, 'unique skills increase transfer score');
cup.landed('floor'); assert.equal(cup.score, 220, 'landing alone scores nothing');
cup.tick(60); assert.equal(cup.next(), false); assert.equal(cup.history.length, 3);
assert.equal(cup.totals[0], 1520); assert.equal(new context.GravityCup().best.style, 220);
cup.start('style'); cup.tick(3); cup.skill('flip'); cup.landed('ceil');
assert.equal(cup.score, 0, 'toggle spam without jumping scores nothing');
saved['gravity-cup-best'] = '"broken"'; assert.deepEqual(Object.keys(new context.GravityCup().best), []);
console.log('Tournament rules passed: countdown, scoring, combo expiry, pause, medals, progression, skill variety, persistence and duplicate prevention.');
