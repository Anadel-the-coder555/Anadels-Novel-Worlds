const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const saved = {};
const context = { localStorage: { getItem: k => saved[k], setItem: (k, v) => saved[k] = v } };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'adventure.js'), 'utf8'), context);
const adv = new context.Adventure();
assert.equal(adv.total, 8, 'eight shards in the story'); assert.equal(adv.found, 0);
assert.equal(adv.shardsIn('living'), null, 'shards only appear for the current step');
assert.equal(adv.shardsIn('arduan').length, 1);
assert.equal(adv.collect(5), false, 'unknown shard is ignored');
assert.equal(adv.collect(0), true); assert.equal(adv.collect(0), false, 'a shard counts once');
adv.next(); assert.equal(adv.step.to, 'living'); assert.equal(adv.found, 1);
adv.next(); assert.equal(adv.collect(1), false); assert.equal(adv.shardsIn('living').map(q => q.i).join(), '0', 'collected shards stay gone');
const resumed = new context.Adventure(); assert.equal(resumed.i, 2); assert.equal(resumed.found, 2, 'progress survives a reload');
while (resumed.step.type !== 'catch') resumed.next();
assert.equal(resumed.collect(0), false); assert.equal(resumed.collect(0), false); assert.equal(resumed.collect(0), true);
assert.equal(resumed.collect(0), false, 'no fourth catch'); assert.equal(resumed.found, 8);
resumed.next(); assert.equal(resumed.done, true); resumed.next(); assert.equal(resumed.done, true, 'the end stays the end');
assert.equal(resumed.lock('school', 'atrium'), null, 'all doors open after the story');
resumed.reset(); assert.equal(new context.Adventure().i, 0);
saved['gravity-adventure'] = '{"i":99}'; assert.equal(new context.Adventure().i, 0, 'bad save is ignored');
console.log('Adventure rules passed: shard counting, step order, door locks, catches, save/resume, reset and bad saves.');
